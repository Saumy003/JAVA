public class IfElse_Statement {
    
    public static void main(String[] args) {
        
        // Example 1

        int marks = 35;

        if (marks >= 40) {
            System.out.println("Pass");
        } else {
            System.out.println("Fail");
        }

        // Example 2

        int age = 12;

        if (age >= 18) {
            System.out.println("Can Vote!");
        }
        else {
            System.out.println("Cannot Vote!");
        }
    }
}