public class Unary {
    
    public static void main(String[] args) {
        
        int a = 10;
        System.out.println(++a);

        int d = 10;
        System.out.println(d--);

        int b = 5;
        System.out.println(--b);

        int c = 5;
        System.out.println(c--);
    }
}
