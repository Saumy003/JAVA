public class Arithmetic {

    public static void main(String[] args) {
        
        int a = 25;
        int b = 15;

        int total = a + b;
        int difference = a - b;
        int projected = a * 4;
        int average = a / 7;
        int remainder = a % 7;

        System.out.println(total);
        System.out.println(difference);
        System.out.println(projected);
        System.out.println(average);
        System.out.println(remainder);
    }
    
}
